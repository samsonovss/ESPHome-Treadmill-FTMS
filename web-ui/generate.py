#!/usr/bin/env python3
"""Deterministic offline single-document/header generator; no remote assets."""
import hashlib
import json
from pathlib import Path
p = Path(__file__).resolve().parent
# 17.10: built-in routes removed from the firmware — the page only knows routes saved on the treadmill
map_profiles = {'options':['None'],'routes':{}}
html = (p/'index.html').read_text()
locales = {lang:json.loads((p/'locales'/f'{lang}.json').read_text()) for lang in ['ru','en']}
import re
_c=(p/'preview'/'concept'/'index.html').read_text()
_css=re.sub(r'(?<![\w.#-])body\{',':host{display:block;',re.sub(r'(?<![\w.#-]):root\{',':host{',re.search(r'<style>(.*?)</style>',_c,re.S).group(1)))
_body=re.search(r'<body>(.*?)<script>',_c,re.S).group(1)
_js=re.search(r'<script>(.*?)</script>',_c,re.S).group(1).replace("'use strict';",'').replace('document.getElementById(id)','__root.getElementById(id)').replace('document.documentElement','__host')
concept_js='// Concept training page (preview/concept/index.html), embedded 1:1 in a shadow root. DEMO data only.\nconst ConceptPage={mount(host,__api){const __root=host.attachShadow({mode:"open"}),__host=host;__root.innerHTML="<style>"+'+json.dumps(_css)+'+"</style>"+'+json.dumps(_body)+';\n'+_js+'\n}};\n'
for marker, body in [('STYLE',(p/'style.css').read_text()),
                     ('LOCALES','const LOCALES = '+json.dumps(locales,ensure_ascii=False,separators=(',',':'))+';'),
                     ('THEME',(p/'theme.js').read_text()),
                     ('CONTROLS',(p/'diag.js').read_text()+'\n'+(p/'controls.js').read_text()),
                     ('DATA','const MAP_PROFILES = '+json.dumps(map_profiles,ensure_ascii=False,separators=(',',':'))+';\n'+(p/'fit.js').read_text()+'\n'+(p/'history.js').read_text()),
                     ('PAGE',(p/'routes-lib.js').read_text()+'\n'+(p/'routes-map.js').read_text()+'\n'+concept_js+'\n'+(p/'concept-live.js').read_text()),
                     ('APP',(p/'settings.js').read_text()+'\n'+(p/'app.js').read_text())]:
    assert html.count('/*'+marker+'*/') == 1
    html = html.replace('/*'+marker+'*/', body)
assert ')TREADUI"' not in html
import gzip as _gz
_raw=_gz.compress(html.encode('utf-8'),compresslevel=9,mtime=0)
_ver=hashlib.sha1(_raw).hexdigest()[:16]
gz_bytes=','.join(('\n' if i%32==0 else '')+str(b) for i,b in enumerate(_raw))
header = '''// GENERATED by generate.py; edit web-ui source files instead.
#pragma once
#include "esphome/components/web_server_base/web_server_base.h"
namespace treadmill_web {
// gzip of the page (browsers inflate it themselves): ~3x less flash and Wi-Fi time than raw HTML.
static const uint8_t DASHBOARD_GZ[] = {'''+gz_bytes+'''};
static const char DASHBOARD_ETAG[] = "\\"'''+_ver+'''\\"";
// "/" = tiny loader (never cached, ~0.5 KB); it fetches "/ui?v=<build>", which the browser keeps for a year.
// New firmware → new build hash → new URL → downloaded once. (ESPHome's IDF server cannot answer 304.)
static const char DASHBOARD_STUB[] = R"TREADSTUB(<!doctype html><html lang="ru"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Treadmill</title><body style="margin:0;background:#0d0f13;color:#8a93a3;font:14px system-ui;display:grid;place-items:center;height:100vh"><div id="l">Загрузка…</div><script>
fetch('/ui?v='''+_ver+'''',{cache:'force-cache'}).then(r=>{if(!r.ok)throw Error(r.status);return r.text();}).then(h=>{document.open();document.write(h);document.close();}).catch(e=>{document.getElementById('l').innerHTML='Не удалось загрузить интерфейс ('+e.message+') · <a href="/" style="color:#4da3ff">ещё раз</a>';});
</script>)TREADSTUB";
class DashboardHandler : public AsyncWebHandler {
 public:
  bool canHandle(AsyncWebServerRequest *request) const override {
    char buffer[AsyncWebServerRequest::URL_BUF_SIZE];
    auto url = request->url_to(buffer);
    return request->method() == HTTP_GET && (url == "/" || url == "/ui");
  }
  void handleRequest(AsyncWebServerRequest *request) override {
    char buffer[AsyncWebServerRequest::URL_BUF_SIZE];
    const bool stub = request->url_to(buffer) == "/";
    auto *response = stub
        ? request->beginResponse(200, "text/html; charset=utf-8", (const uint8_t *) DASHBOARD_STUB, sizeof(DASHBOARD_STUB) - 1)
        : request->beginResponse(200, "text/html; charset=utf-8", DASHBOARD_GZ, sizeof(DASHBOARD_GZ));
    if (!stub) response->addHeader("Content-Encoding", "gzip");
    response->addHeader("Cache-Control", stub ? "no-store" : "public, max-age=31536000, immutable");
    response->addHeader("X-Content-Type-Options", "nosniff");
    response->addHeader("Content-Security-Policy", "default-src 'none'; script-src 'unsafe-inline' https://unpkg.com; style-src 'unsafe-inline' https://unpkg.com; img-src https://tile.openstreetmap.org https://unpkg.com https://cdn.zwift.com data:; connect-src 'self' https://brouter.de https://nominatim.openstreetmap.org https://api.open-meteo.com https://raw.githubusercontent.com https://api.github.com; base-uri 'none'; form-action 'none'; frame-ancestors 'none'");
    request->send(response);
  }
};
inline DashboardHandler dashboard_handler;
inline bool handler_registered = false;
inline void register_web_handler() {
  if (handler_registered || esphome::web_server_base::global_web_server_base == nullptr) return;
  esphome::web_server_base::global_web_server_base->add_handler(&dashboard_handler);
  handler_registered = true;
}
} // namespace treadmill_web
'''
(p/'generated').mkdir(exist_ok=True)
# Demo build (GitHub Pages): the same page + demo/mock.js, a virtual treadmill that answers /events and the API in the browser.
_core=p.parent/'esphome'/'packages'/'00-core.yaml'
_ver=re.search(r'version:\s*"([^"]+)"',_core.read_text()).group(1) if _core.exists() else 'demo'
_mock=(p/'demo'/'mock.js').read_text().replace('/*DEMO_ENTITIES*/[]',(p/'demo'/'entities.json').read_text().strip()).replace("/*DEMO_VERSION*/''",json.dumps(_ver)).replace('/*DEMO_HISTORY*/[]',(p/'demo'/'history.json').read_text().strip()).replace('/*DEMO_ROUTES*/{}',(p/'demo'/'routes.json').read_text().strip())
assert html.count('<head>')==1 and '</script' not in _mock
(p/'generated/demo.html').write_text(html.replace('<head>','<head><script>'+_mock+'</script>',1))
(p/'generated/index.html').write_text(html)
# The firmware includes the header from esphome/ (next to treadmill.yaml) in the repository; elsewhere it stays in generated/.
out = p.parent/'esphome' if (p.parent/'esphome'/'packages').is_dir() else p/'generated'
(out/'treadmill_dashboard.h').write_text(header)
print(f'Generated offline HTML {len(html.encode())} bytes; header {len(header.encode())} bytes')
